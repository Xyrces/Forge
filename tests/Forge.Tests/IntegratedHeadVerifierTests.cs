namespace Forge.Tests;

public sealed class IntegratedHeadVerifierTests
{
    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ExactIntegrationUsesOneDurableZeroModelVerifierAndProtectedAuthority(bool alreadyMerged)
    {
        var root = TempRoot.Instance.NewDirectory("integrated-head");
        var bare = root + "-origin";
        await Git(root, "init", "-b", "main"); await Git(root, "config", "user.name", "Test");
        await Git(root, "config", "user.email", "test@example.com");
        File.WriteAllText(Path.Combine(root, "base.txt"), "base");
        await Git(root, "add", "-A"); await Git(root, "commit", "-m", "base");
        await Git(root, "clone", "--bare", root, bare); await Git(root, "remote", "add", "origin", bare);
        await Git(root, "checkout", "-b", "feature"); File.WriteAllText(Path.Combine(root, "feature.txt"), "feature");
        await Git(root, "add", "-A"); await Git(root, "commit", "-m", "feature");
        var original = await Git(root, "rev-parse", "HEAD"); var originalTree = await Git(root, "rev-parse", "HEAD^{tree}");
        await Git(root, "checkout", "main"); File.WriteAllText(Path.Combine(root, "upstream.txt"), "upstream");
        await Git(root, "add", "-A"); await Git(root, "commit", "-m", "upstream"); await Git(root, "push", "origin", "main");
        var basis = await Git(root, "rev-parse", "HEAD");
        await Git(root, "checkout", "feature"); await Git(root, "merge", "--no-ff", "main", "-m", "integration");
        await Git(root, "push", "origin", "feature"); var head = await Git(root, "rev-parse", "HEAD");
        var mergeSha = head;
        if (alreadyMerged)
        {
            await Git(root, "checkout", "main"); await Git(root, "merge", "--no-ff", "feature", "-m", "merge-pr");
            mergeSha = await Git(root, "rev-parse", "HEAD"); await Git(root, "push", "origin", "main");
        }
        IReadOnlyList<string> commands = ["git diff --exit-code"];
        await using var issues = new IssueStore(Path.Combine(root, "state.db"), "forge");
        // Exclude task DB and snapshots from prospective verification trees.
        File.AppendAllText(Path.Combine(root, ".git", "info", "exclude"), "\nstate.db*\n.wt/\n");
        var task = await issues.CreateAsync(new Forge.Core.NewIssue("task", "Integration", Metadata: new Dictionary<string, object>
        { ["prNumber"] = 9, ["branch"] = "feature", ["branchSha"] = original,
          ["trustedPublication"] = JsonSerializer.Serialize(new TrustedPublicationEvidence("task-1", original,
            new("original-attempt", originalTree, WorkerVerification.CommandsHash(commands), DateTimeOffset.UtcNow))) }));
        // IDs are generated by the store; bind publication to the actual task.
        await issues.TransitionAsync(task.Id, alreadyMerged ? IssueStatus.Completed : IssueStatus.InProgress, null,
            new Dictionary<string, object> { ["trustedPublication"] = JsonSerializer.Serialize(new TrustedPublicationEvidence(task.Id, original,
                new("original-attempt", originalTree, WorkerVerification.CommandsHash(commands), DateTimeOffset.UtcNow))),
                ["observedMerge"] = alreadyMerged ? JsonSerializer.Serialize(new ObservedMergeEvidence(task.Id, 9, head, mergeSha, DateTimeOffset.UtcNow)) : null! });
        task = (await issues.GetAsync(task.Id))!; var originalJson = task.GetMetadata("trustedPublication");
        var attempts = new WorkerAttemptStore(issues.Db); var jobs = new Jobs(attempts);
        var github = new GitHub(head, basis, alreadyMerged, mergeSha);
        var worktrees = new GitWorktreeService(new WorkspaceOptions { Root = root, WorktreeRoot = ".wt", DefaultBranch = "main" }, NullLogger<GitWorktreeService>.Instance);
        IntegratedHeadVerifier Verifier() => new(issues, worktrees, github, new KubernetesAgentRunner(attempts, jobs, "dataset"), "forge", commands, NullLogger<IntegratedHeadVerifier>.Instance);
        Assert.False(await Verifier().EnsureAsync(task, alreadyMerged ? null : head, default));
        Assert.True(jobs.Assignment is not null, (await issues.GetAsync(task.Id))!.GetMetadata("reviewIntegrationVerificationError")); var assignment = jobs.Assignment!;
        Assert.True(JsonSerializer.Deserialize<WorkerInvocation>(assignment.AssignmentJson)!.VerificationOnly);
        var proof = await WorkerVerification.VerifyAsync(assignment.Id, assignment.WorktreePath, commands, NullLogger.Instance, default);
        await attempts.CompleteAsync(assignment.Id, "pod", assignment.AttemptToken,
            JsonSerializer.Serialize(new AgentRunResult("", null, 0, 0, TimeSpan.Zero, Verification: proof)), null);
        // Replacement controller adopts completed worker instead of creating a new Job.
        Assert.True(await Verifier().EnsureAsync(task, alreadyMerged ? null : head, default));
        var current = (await issues.GetAsync(task.Id))!;
        Assert.Equal(originalJson, current.GetMetadata("trustedPublication")); Assert.Equal(original, current.GetMetadata("branchSha"));
        var integrated = TaskDeliveryEvidence.Integration(current, head); Assert.NotNull(integrated);
        var authority = await new MemoryStore(issues.Db).GetAsync(TaskDeliveryEvidence.IntegrationAuthorityKey("forge", task.Id, head));
        Assert.Equal(JsonSerializer.Serialize(integrated), authority!.Body);
        await Assert.ThrowsAsync<ArgumentException>(() => new MemoryStore(issues.Db).RememberAsync(authority.Key, "forged"));
        Assert.False(Directory.Exists(assignment.WorktreePath)); Assert.Equal(1, jobs.Created);
        Assert.True(await Verifier().EnsureAsync(current, head, default)); Assert.Equal(1, jobs.Created);
        Assert.False(await Verifier().EnsureAsync(current, new string('a', 40), default));
        if (alreadyMerged) Assert.True(TaskDeliveryEvidence.IsMergedAndVerified(current));
    }

    private sealed class Jobs(WorkerAttemptStore store) : IWorkerJobs
    {
        public int Created; public WorkerAssignment? Assignment;
        public async Task EnsureJobAsync(WorkerAssignment a, CancellationToken ct) { Created++; Assignment = a; await store.ClaimAsync(a.Id, "pod", ct); }
        public Task<string?> GetFailureAsync(string id, CancellationToken ct) => Task.FromResult<string?>(null);
        public Task CancelAndWaitAsync(string id, CancellationToken ct) => Task.CompletedTask;
    }
    private sealed class GitHub(string head, string basis, bool merged, string mergeSha) : GitHubService("owner", "repo", null)
    {
        public override Task<PullRequest> GetPullRequestAsync(int number, CancellationToken cancellationToken = default)
        {
            var repo = new Repository(); Set(repo, "FullName", "owner/repo"); var pr = new PullRequest(number);
            Set(pr, "Head", new GitReference(null!, null!, null!, "feature", head, null!, repo));
            Set(pr, "Base", new GitReference(null!, null!, null!, "main", basis, null!, repo));
            Set(pr, "State", new StringEnum<ItemState>(merged ? ItemState.Closed : ItemState.Open));
            if (merged) Set(pr, "MergedAt", DateTimeOffset.UtcNow); Set(pr, "MergeCommitSha", merged ? mergeSha : null!); return Task.FromResult(pr);
        }
    }
    private static void Set(object target, string property, object value) => target.GetType().GetProperty(property)!.SetValue(target, value);
    private static async Task<string> Git(string path, params string[] args)
    {
        var start = new ProcessStartInfo("git") { WorkingDirectory = path, RedirectStandardOutput = true, RedirectStandardError = true };
        foreach(var arg in args) start.ArgumentList.Add(arg);
        using var process = Process.Start(start)!; var output = process.StandardOutput.ReadToEndAsync(); var error = process.StandardError.ReadToEndAsync();
        await process.WaitForExitAsync(); Assert.True(process.ExitCode == 0, await error); return (await output).Trim();
    }
}
