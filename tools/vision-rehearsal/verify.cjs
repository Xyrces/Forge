// Run: NODE_PATH=/path/to/node_modules node verify.cjs <output-dir>
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
(async () => {
  const out = process.argv[2];
  assert(out, 'output directory required');
  fs.mkdirSync(out, { recursive: true });
  const base = process.env.VISION_URL || 'http://127.0.0.1:5126';
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE_PATH, headless: true });
  const page = await browser.newPage({ viewport: { width: 2560, height: 1274 } });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  const json = async url => { const r = await page.request.get(base + url); assert(r.ok(), await r.text()); return r.json(); };
  const evidence = () => json('/__qualification/evidence');
  const original = await json('/api/projects/forge/vision/map');
  assert.equal(original.nodes.map(n => n.text).join(''), original.source, 'all source segments preserved');
  assert.equal(crypto.createHash('sha256').update(original.source).digest('hex'), '58aa439003de01daa72840d4d3c68159e3f35c10da802c3f0402ede96f55efde');
  assert.equal(Buffer.byteLength(original.source), 50945);
  await page.goto(base + '/vision');
  await page.locator('#vision-message').waitFor();
  await page.locator('.vision-map-node').first().waitFor();
  assert.equal(await page.locator('.vision-map-node[aria-pressed="true"]').count(), 0, 'no selected node');
  for (const id of ['purpose', 'engineering', 'work', 'references'])
    await page.locator(`[data-node="group:${id}"]`).waitFor();
  await page.screenshot({ path: path.join(out, 'desktop-initial.png'), fullPage: true });
  const send = async text => {
    await page.locator('#vision-message').fill(text);
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.getByRole('button', { name: 'Apply draft', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('#vision-message').value === '');
  };
  await send('Require UAT before sprint completion and show the blocking acceptance check.');
  assert.equal(await page.locator('.vision-change').count(), 2);
  assert.equal((await evidence()).source, original.source, 'proposal must not write');
  await page.screenshot({ path: path.join(out, 'desktop-proposal.png'), fullPage: true });
  await send('Keep only the sprint completion change.');
  assert.equal(await page.locator('.vision-change').count(), 1);
  await page.reload();
  await page.getByRole('button', { name: 'Apply draft', exact: true }).waitFor();
  assert.equal(await page.locator('.vision-change').count(), 1, 'draft restored after reload');
  assert.equal((await evidence()).source, original.source);
  await page.getByRole('button', { name: 'Apply draft', exact: true }).click();
  await page.getByRole('button', { name: 'Apply draft', exact: true }).waitFor({ state: 'hidden' });
  const applied = await evidence();
  const expected = original.source.replace('when every member task is terminal', 'when every member task is terminal and the sprint release passes UAT');
  assert.equal(applied.source, expected, 'disk contains precisely approved edit');
  assert.equal(applied.memory, expected, 'owning prompt memory matches disk');
  assert.equal(applied.other, '# Other project\n\nIndependent vision.\n', 'other project untouched');
  assert(applied.calls.every(c => c.project === 'forge' && c.role === 'Intake' && c.structured && c.tools === 0));
  assert.equal(applied.calls[0].source, original.source, 'actual agent sent whole source to provider');
  await send('Propose another refinement.');
  await page.getByRole('button', { name: 'Discard draft', exact: true }).click();
  await page.getByRole('button', { name: 'Apply draft', exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await evidence()).source, expected, 'discard must not write');
  await page.locator('#vision-message').fill('Exercise provider failure.');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.getByText('Message could not be completed.', { exact: false }).waitFor();
  assert.equal(await page.locator('#vision-message').inputValue(), 'Exercise provider failure.');
  assert.equal((await evidence()).source, expected);
  // Stale approval uses the actual endpoint, never a mocked browser response.
  const stale = await page.request.post(base + '/api/projects/forge/vision/apply', { data: {
    baseRevision: original.revision, edits: [{ nodeId: 'root', operation: 'append', before: '', after: 'stale' }] } });
  assert.equal(stale.status(), 409);
  assert.equal((await evidence()).source, expected);
  await page.locator('.project-switcher__select').selectOption('other');
  await page.waitForFunction(() => document.querySelector('#vision-message')?.value === '');
  await send('Add an independent refinement.');
  await page.getByRole('button', { name: 'Apply draft', exact: true }).click();
  await page.getByRole('button', { name: 'Apply draft', exact: true }).waitFor({ state: 'hidden' });
  assert.equal((await evidence()).source, expected, 'secondary apply cannot change primary');
  assert((await evidence()).other.includes('Qualification draft only'));
  await page.locator('.project-switcher__select').selectOption('forge');
  await page.waitForFunction(() => document.querySelector('#vision-message')?.value === 'Exercise provider failure.');
  await send('Add a new root idea.');
  await page.getByRole('button', { name: 'Full map', exact: true }).click();
  const newBranch = page.locator('.vision-map-node').filter({ hasText: 'Qualification new branch' });
  await newBranch.waitFor();
  await page.getByRole('button', { name: 'Apply draft', exact: true }).click();
  await page.getByRole('button', { name: 'Apply draft', exact: true }).waitFor({ state: 'hidden' });
  await newBranch.waitFor();
  const withBranch = (await evidence()).source;
  assert(withBranch.includes('## Qualification new branch'));
  await page.getByRole('button', { name: 'Source document', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Markdown', exact: true }).click();
  const rawDraft = withBranch + '\nRaw editor large-document regression.\n';
  await page.locator('#vision-source-text').fill(rawDraft);
  await page.waitForFunction(text => JSON.parse(sessionStorage.getItem('forge.vision.conversation.v1.forge')).sourceDraft === text, rawDraft);
  assert.equal((await evidence()).source, withBranch, 'raw draft must not write before Save');
  await page.reload();
  await page.locator('#vision-source-text').waitFor();
  assert.equal(await page.locator('#vision-source-text').inputValue(), rawDraft, '>32KiB raw source restored');
  await page.getByRole('button', { name: 'Save source', exact: true }).click();
  await page.locator('#vision-source-text').waitFor({ state: 'hidden' });
  assert.equal((await evidence()).source, rawDraft);
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  assert.equal((await evidence()).source, rawDraft, 'refresh must retain saved project vision');
  await page.getByRole('button', { name: 'Edit Markdown', exact: true }).click();
  await page.getByRole('button', { name: 'Load repository Markdown', exact: true }).click();
  await page.waitForFunction(text => document.querySelector('#vision-source-text')?.value === text, original.source);
  assert.equal(await page.locator('#vision-source-text').inputValue(), original.source);
  assert.equal((await evidence()).source, rawDraft, 'repository import is a preview until saved');
  await page.getByRole('button', { name: 'Cancel edit', exact: true }).click();
  await page.locator('#vision-source-text').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => JSON.parse(sessionStorage.getItem('forge.vision.conversation.v1.forge')).sourceDraft === null);
  // Real session restoration transports a large conversation back over Blazor.
  await page.evaluate(() => {
    const key = 'forge.vision.conversation.v1.forge';
    const session = JSON.parse(sessionStorage.getItem(key));
    session.messages.push({ role: 'assistant', text: 'large-history-marker ' + 'History grounding. '.repeat(2500) });
    sessionStorage.setItem(key, JSON.stringify(session));
  });
  await page.reload();
  await page.getByText('large-history-marker', { exact: false }).waitFor();
  await page.locator('#vision-message').fill('Still connected after large history.');
  await page.waitForFunction(() => JSON.parse(sessionStorage.getItem('forge.vision.conversation.v1.forge')).input === 'Still connected after large history.');
  assert.equal((await evidence()).source, rawDraft);
  // Mobile qualification uses Forge's full map as well as the secondary project.
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.reload();
    await page.locator('#vision-message').waitFor();
    await page.locator('.vision-map-node').first().waitFor();
    const sizes = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
    assert(sizes.scroll <= sizes.width + 1, `mobile overflow at ${width}: ${JSON.stringify(sizes)}`);
    await page.locator('.vision-map-node').first().click();
    await page.getByRole('region', { name: 'Selected idea' }).waitFor();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(out, `mobile-${width}.png`), fullPage: true });
  }
  assert.deepEqual(errors, []);
  const final = await evidence();
  assert.equal(final.repoSource, original.source, 'project checkout unchanged after approved conversation/raw changes');
  assert.equal(final.repoOther, '# Other project\n\nIndependent vision.\n');
  assert.deepEqual(final.gitStatus, ['', ''], 'planning checkout remains clean in both projects');
  fs.writeFileSync(path.join(out, 'evidence.json'), JSON.stringify({ sourceHash: original.revision, nodes: original.nodes.length,
    browserErrors: errors, assertions: 'lossless source, unselected chat, complete-draft followup, reload, approval, persisted project vision and memory, pristine git checkouts, discard, provider failure, stale approval, project isolation, root branch, raw editor and large history transport, repository preview, mobile' }, null, 2));
  await browser.close();
  console.log('Vision qualification passed.');
})().catch(e => { console.error(e); process.exit(1); });
