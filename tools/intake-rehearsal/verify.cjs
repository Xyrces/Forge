const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const out = process.argv[2];
if (!out) throw new Error('Evidence directory required');
fs.mkdirSync(out, { recursive: true });
const base = process.env.INTAKE_URL || 'http://127.0.0.1:5127';
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
  const page = await browser.newPage({viewport:{width:2560,height:1274},colorScheme:'dark'});
  const errors=[];
  page.on('pageerror', e=>errors.push(String(e)));
  const get = async url=>{const r=await page.request.get(base+url);assert(r.ok(),await r.text());return r.json();};
  const evidence=()=>get('/__qualification/evidence');
  const seed=await get('/__qualification/seed');
  const brief=page.getByRole('region',{name:'Working brief',exact:true});
  const button=(name)=>page.getByRole('button',{name,exact:true});
  const shot=async name=>page.screenshot({path:path.join(out,name+'.png'),fullPage:true});
  const check=async label=>{
    const sizes=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
    assert(sizes.scroll<=sizes.width+1,`${label}: page overflow ${JSON.stringify(sizes)}`);
    assert.deepEqual(errors,[],label+': browser errors');
  };
  await page.goto(base+'/intake?project=forge');
  await page.getByRole('region',{name:'Intake inbox',exact:true}).waitFor();
  await page.getByRole('button',{name:/Clear release evidence/}).waitFor();
  assert.equal(await page.locator('#intake-message').count(),0,'default is inbox, not resumed conversation');
  assert.equal(await page.getByText('Other project private brief',{exact:true}).count(),0);
  await shot('inbox-desktop');
  await button('New idea').click();
  await page.locator('#intake-message').fill('Keep the operator informed about release verification.');
  await button('Send').click();
  await page.getByText("Let's clarify the desired outcome and what would count as success. Nothing has been approved.",{exact:true}).waitFor();
  assert.equal((await evidence()).calls,1);
  await page.locator('#intake-message').fill('Draft the release verification brief.');
  await button('Send').click();
  await page.getByRole('heading',{name:'Release verification from conversation',exact:true}).waitFor();
  assert.equal((await evidence()).forgeIssues.length,0,'tool-created brief stays unapproved');
  const conversationUrl=page.url();
  await page.reload();
  await page.getByText('Keep the operator informed about release verification.',{exact:true}).waitFor();
  await page.getByRole('button',{name:/Back to Intake/}).click();
  await page.getByRole('region',{name:'Intake inbox',exact:true}).waitFor();
  await page.getByRole('button',{name:/Clear release evidence/}).click();
  await page.getByRole('heading',{name:'Clear release evidence',exact:true}).waitFor();
  await brief.getByLabel('Brief in this conversation').selectOption(seed.sibling.id);
  await page.getByRole('heading',{name:'Keep the evidence readable',exact:true}).waitFor();
  await brief.getByRole('button',{name:'Changes',exact:true}).click();
  await brief.getByText('This is the first revision. Review the complete brief below.').waitFor();
  await brief.getByLabel('Brief in this conversation').selectOption(seed.revised.id);
  await brief.getByRole('button',{name:'Changes',exact:true}).click();
  await brief.getByText('Revision 1 compared with revision 2',{exact:true}).waitFor();
  await shot('comparison-desktop');
  await brief.getByRole('button',{name:'Current brief',exact:true}).click();
  let e=await evidence();assert.equal(e.forgeIssues.length,0);assert.equal(e.forgeSpecs.length,0);
  await brief.getByRole('button',{name:'Approve revision 2',exact:true}).click();
  await brief.getByRole('link',{name:'Open specification',exact:true}).waitFor();
  e=await evidence();
  assert.deepEqual(e.approvalRequests[0],{revision:seed.revised.revision,hash:seed.revised.hash});
  assert.equal(e.forgeIssues.length,1);assert.equal(e.forgeSpecs.length,1);
  assert.equal(e.otherIssues.length,0);assert.equal(e.otherSpecs.length,0);assert.equal(e.sprints.length,0);
  assert.equal(e.receipt.revision,2);assert.equal(e.receipt.hash,seed.revised.hash);assert.equal(e.receipt.refinementState,'Pending');
  const href=await brief.getByRole('link',{name:'Open specification',exact:true}).getAttribute('href');
  assert.equal(href,`/specs/${e.receipt.specId}?project=forge`);
  const repeat=await page.request.post(base+`/api/intake/proposals/${seed.revised.id}/approve?projectId=forge`,{data:{revision:2,hash:seed.revised.hash}});
  assert(repeat.ok(),await repeat.text());assert.equal((await evidence()).forgeIssues.length,1);
  await page.reload();await brief.getByRole('link',{name:'Open specification',exact:true}).waitFor();
  await shot('approved-handoff-desktop');
  // Concurrent editor changes the proposal after the UI reads it.
  await brief.getByLabel('Brief in this conversation').selectOption(seed.sibling.id);
  await brief.getByRole('button',{name:'Approve revision 1',exact:true}).waitFor();
  assert((await page.request.post(base+`/__qualification/revise/${seed.sibling.id}`)).ok());
  await brief.getByRole('button',{name:'Approve revision 1',exact:true}).click();
  await brief.getByText('The brief changed while you were reviewing it. Refresh the brief and review the latest revision before approving.',{exact:true}).waitFor();
  assert(await brief.getByRole('button',{name:'Approve revision 1',exact:true}).isDisabled());
  assert.equal((await evidence()).forgeIssues.length,1);
  await brief.getByRole('button',{name:'Refresh brief',exact:true}).click();
  await brief.getByRole('button',{name:'Approve revision 2',exact:true}).waitFor();
  assert(await brief.getByRole('button',{name:'Approve revision 2',exact:true}).isEnabled());
  const wrong=await page.request.get(base+`/api/intake/proposals/${seed.revised.id}?projectId=other`);assert.equal(wrong.status(),404);
  await page.goto(base+'/intake?project=other');
  await page.getByRole('button',{name:/Other project private brief/}).waitFor();
  assert.equal(await page.getByRole('button',{name:/Clear release evidence/}).count(),0);
  await page.goto(base+`/intake?project=forge&session=${seed.session.id}&proposal=${seed.revised.id}`);
  await brief.getByRole('link',{name:'Open specification',exact:true}).waitFor();
  for (const width of [1024,320]) {
    await page.setViewportSize({width,height:900});
    await check('workspace '+width);await shot('workspace-'+width);
    await page.getByRole('button',{name:/Back to Intake/}).click();
    await page.getByRole('region',{name:'Intake inbox',exact:true}).waitFor();
    await check('inbox '+width);await shot('inbox-'+width);
    await page.goto(base+`/intake?project=forge&session=${seed.session.id}&proposal=${seed.revised.id}`);
    await brief.getByRole('link',{name:'Open specification',exact:true}).waitFor();
  }
  await check('complete');
  fs.writeFileSync(path.join(out,'result.json'),JSON.stringify({passed:true,checks:['inbox','new conversation','tool-produced linked draft','reload/resume','return','proposal selection','revision comparison','exact revision/hash approval','real atomic epic/spec/receipt','idempotency','stale conflict and explicit refresh','project isolation','scoped handoff','1024/320 layout'],conversationUrl,evidence:await evidence(),errors},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
